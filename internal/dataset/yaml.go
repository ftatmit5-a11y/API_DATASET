package dataset

import (
	"fmt"
	"os"
	"strings"
)

func writeDataYAML(path string, names []string, includeVal, includeTest bool) error {
	var b strings.Builder
	b.WriteString("# Generated by YOLO Dataset API\n")
	b.WriteString("path: .\n")
	b.WriteString("train: train/images\n")
	if includeVal {
		b.WriteString("val: val/images\n")
	}
	if includeTest {
		b.WriteString("test: test/images\n")
	}
	b.WriteString("\n")
	fmt.Fprintf(&b, "nc: %d\n", len(names))
	b.WriteString("names:\n")
	for i, name := range names {
		fmt.Fprintf(&b, "  %d: %s\n", i, yamlScalar(name))
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func yamlScalar(s string) string {
	if s == "" {
		return `""`
	}
	if strings.ContainsAny(s, ":#{}[]&*!|>'\"%@`,\n\t") || strings.HasPrefix(s, " ") || strings.HasSuffix(s, " ") || looksNumeric(s) {
		return strconvQuote(s)
	}
	for _, r := range s {
		if r < 0x20 {
			return strconvQuote(s)
		}
	}
	return s
}

func looksNumeric(s string) bool {
	if s == "true" || s == "false" || s == "null" || s == "~" || s == "yes" || s == "no" {
		return true
	}
	dot := false
	for i, r := range s {
		switch {
		case r >= '0' && r <= '9':
		case r == '-' && i == 0:
		case r == '.' && !dot:
			dot = true
		default:
			return false
		}
	}
	return true
}

func strconvQuote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '\\', '"':
			b.WriteByte('\\')
			b.WriteRune(r)
		case '\n':
			b.WriteString(`\n`)
		case '\t':
			b.WriteString(`\t`)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}
